// Evenfield i18n. Two locales, full template coverage. Names that are never
// translated: Evenfield, the module names (Rush, Lookout, Launchparty,
// Potluck, Goodname, Bandwagon), token names and symbols, addresses.
// All numbers go through Intl.NumberFormat for the active locale and all
// dates through Intl.DateTimeFormat (blueprint G13). Verdict and passport
// sentences are per-locale templates with named slots, never word-by-word
// runtime translation.

export type Lang = 'en' | 'id';
const LS_LANG = 'evenfield.v1.lang';
let lang: Lang = 'en';
try {
  const saved = localStorage.getItem(LS_LANG);
  if (saved === 'id' || saved === 'en') lang = saved;
} catch { /* memory-only */ }

export function getLang(): Lang { return lang; }
export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem(LS_LANG, l); } catch { /* ignore */ }
  document.documentElement.lang = l === 'id' ? 'id' : 'en';
}
export function localeTag(): string { return lang === 'id' ? 'id-ID' : 'en-US'; }

export function fmtNum(v: number, opts?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(localeTag(), opts).format(v);
}
export function fmtCompact(v: number): string {
  return new Intl.NumberFormat(localeTag(), { notation: 'compact', maximumFractionDigits: 1 }).format(v);
}
export function fmtDateTime(d: Date): string {
  return new Intl.DateTimeFormat(localeTag(), { dateStyle: 'medium', timeStyle: 'short' }).format(d);
}
export function fmtAgo(then: Date, now = new Date()): string {
  const secs = Math.max(0, Math.round((now.getTime() - then.getTime()) / 1000));
  const rtf = new Intl.RelativeTimeFormat(localeTag(), { numeric: 'auto' });
  if (secs < 90) return rtf.format(-secs, 'second');
  const mins = Math.round(secs / 60);
  if (mins < 90) return rtf.format(-mins, 'minute');
  const hours = Math.round(mins / 60);
  if (hours < 36) return rtf.format(-hours, 'hour');
  return rtf.format(-Math.round(hours / 24), 'day');
}

