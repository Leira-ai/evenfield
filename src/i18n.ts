const DICTS: Record<Lang, Dict> = { en: EN, id: ID };
export function t(key: string, slots?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? EN[key] ?? key;
  if (slots) for (const [k, v] of Object.entries(slots)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
